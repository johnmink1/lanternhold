"""Builds infra/deploy/v140/save-checks.sh from infra/lambda (esbuild bundles, so savecheck.js and trust.js go inside).
Usage: python3 infra/deploy/v140/build.py   (needs esbuild on PATH or ESBUILD=..., e.g. ESBUILD='npx --yes esbuild')
Rebuild whenever save.js, admin.js, mail.js, market.js, gulp.js, savecheck.js or trust.js change before the script runs."""
import base64, hashlib, os, subprocess, shlex
here = os.path.dirname(os.path.abspath(__file__)); lam = os.path.join(here, '..', '..', 'lambda')
esb = shlex.split(os.environ.get('ESBUILD', 'esbuild'))
# function: (source, fingerprint strings the LIVE code must contain, so we only replace the version we expect)
FN = {
  'lanternhold-save':   ('save.js',   ['hf=:h', ' AND attribute_not_exists(dv)']),
  'lanternhold-admin':  ('admin.js',  ['alog#', 'POST /admin/unban']),
  'lanternhold-mail':   ('mail.js',   ['payment', 'paladin']),
  'lanternhold-market': ('market.js', ['mkt#', 'paladin']),
  'lanternhold-gulp':   ('gulp.js',   ['gulpd#', 'wt']),
}
parts = []
for fn, (src, fp) in FN.items():
    code = subprocess.check_output(esb + [os.path.join(lam, src), '--bundle', '--minify', '--platform=node', '--format=cjs', '--external:@aws-sdk/*', '--log-level=warning'])
    parts.append((fn, base64.b64encode(code).decode(), hashlib.md5(code).hexdigest(), fp, len(code)))
out = ['''# Lanternhold v140: save checks, daily save snapshots and server-checked payments (John, 27 Nov 2026).
# Paste into AWS CloudShell (us-east-1). Needs John's go. Safe to run twice. Generated by infra/deploy/v140/build.py.
#  1. Turns on point-in-time recovery for lanternhold-saves (any moment of the last 35 days can be restored).
#  2. lanternhold-save: checks each save against the last trusted one (watch mode: SAVECHECK=log saves everything and
#     only records what it would hold), copies the first save of each day and the save an older copy replaces.
#  3. lanternhold-admin: GET /admin/held, GET /admin/saves, POST /admin/restore, POST /admin/held/drop.
#  4. lanternhold-mail, -market, -gulp: payments checked against trusted gold (TRUSTCHECK=log: watch mode), sales
#     credited to the seller. Switch both to refusing later with v140/enforce.sh.
# Checks every live function is the version we expect BEFORE changing anything, backs each one up to ~/lhbak.
set -e
TS=$(date -u +%Y%m%d%H%M); API=nyu3u8gc73; mkdir -p ~/lhbak ~/lhv140 && cd ~/lhv140
SAVES=$(aws dynamodb describe-table --table-name lanternhold-saves --query Table.TableArn --output text)
TRADE=$(aws dynamodb describe-table --table-name lanternhold-trade --query Table.TableArn --output text)
WAL=$(aws lambda get-function-configuration --function-name lanternhold-np --query Environment.Variables.WALLETS --output text)
WALA=$(aws dynamodb describe-table --table-name $WAL --query Table.TableArn --output text)
echo "1/5 checking the live code"
for F in ''' + ' '.join(p[0] for p in parts) + '''; do
  curl -s -o ~/lhbak/$F-$TS.zip "$(aws lambda get-function --function-name $F --query Code.Location --output text)"
  rm -rf live-$F && mkdir live-$F && unzip -q -o ~/lhbak/$F-$TS.zip -d live-$F
done''']
for fn, b64, md5, fp, n in parts:
    out.append('for s in ' + ' '.join(shlex.quote(x) for x in fp) + '; do grep -qF -- "$s" live-' + fn + '/index.js || { grep -q "untrusted gold\\|savecheck\\|held-drop" live-' + fn + '/index.js && echo "' + fn + ': already v140" || { echo "' + fn + ': live code is not the version this script expects. Stopping; nothing changed."; exit 1; }; }; done')
out.append('''echo "2/5 point-in-time recovery"
aws dynamodb update-continuous-backups --table-name lanternhold-saves --point-in-time-recovery-specification PointInTimeRecoveryEnabled=true >/dev/null
echo "3/5 permissions and settings"
role() { aws lambda get-function-configuration --function-name $1 --query Role --output text | sed 's#.*/##'; }
pol() { aws iam put-role-policy --role-name "$(role $1)" --policy-name lanternhold-v140 --policy-document "$2"; }
pol lanternhold-save "{\\"Version\\":\\"2012-10-17\\",\\"Statement\\":[{\\"Effect\\":\\"Allow\\",\\"Action\\":[\\"dynamodb:Query\\",\\"dynamodb:PutItem\\"],\\"Resource\\":\\"$TRADE\\"},{\\"Effect\\":\\"Allow\\",\\"Action\\":\\"dynamodb:GetItem\\",\\"Resource\\":\\"$WALA\\"}]}"
pol lanternhold-mail "{\\"Version\\":\\"2012-10-17\\",\\"Statement\\":[{\\"Effect\\":\\"Allow\\",\\"Action\\":[\\"dynamodb:GetItem\\",\\"dynamodb:UpdateItem\\"],\\"Resource\\":\\"$SAVES\\"}]}"
pol lanternhold-market "{\\"Version\\":\\"2012-10-17\\",\\"Statement\\":[{\\"Effect\\":\\"Allow\\",\\"Action\\":\\"dynamodb:GetItem\\",\\"Resource\\":\\"$SAVES\\"}]}"
pol lanternhold-gulp "{\\"Version\\":\\"2012-10-17\\",\\"Statement\\":[{\\"Effect\\":\\"Allow\\",\\"Action\\":\\"dynamodb:GetItem\\",\\"Resource\\":\\"$SAVES\\"}]}"
setenv() { # setenv <function> KEY=VALUE...: adds variables, keeps the rest
  aws lambda get-function-configuration --function-name $1 --query Environment.Variables --output json > env-$1.json
  F=$1; shift; python3 - "$F" "$@" <<'PY'
import json, sys
f = sys.argv[1]; v = json.load(open('env-' + f + '.json')) or {}
for kv in sys.argv[2:]: k, x = kv.split('=', 1); v[k] = x
json.dump({'Variables': v}, open('env-' + f + '.json', 'w'))
PY
  aws lambda update-function-configuration --function-name $F --environment file://env-$F.json >/dev/null
  aws lambda wait function-updated --function-name $F
}
setenv lanternhold-save WALLETS=$WAL SAVECHECK=log
setenv lanternhold-mail SAVES=lanternhold-saves TRUSTCHECK=log
setenv lanternhold-market SAVES=lanternhold-saves TRUSTCHECK=log
setenv lanternhold-gulp SAVES=lanternhold-saves TRUSTCHECK=log
sleep 10  # IAM policies take a few seconds to apply
echo "4/5 code"
UNDO=""
put() { # put <function> <md5> <base64>
  echo "$3" | base64 -d > $1.js
  [ "$(md5sum < $1.js | cut -c1-32)" = "$2" ] || { echo "$1: the code did not paste cleanly. Stopping; functions before it are updated (undo below)."; echo -e "$UNDO"; exit 1; }
  rm -f $1.zip && cp $1.js index.js && zip -qj $1.zip index.js
  aws lambda update-function-code --function-name $1 --zip-file fileb://$1.zip >/dev/null
  aws lambda wait function-updated --function-name $1
  UNDO="$UNDO\\naws lambda update-function-code --function-name $1 --zip-file fileb://$HOME/lhbak/$1-$TS.zip"
  echo "updated $1"
}''')
for fn, b64, md5, fp, n in parts:
    out.append('put ' + fn + ' ' + md5 + ' ' + b64)
out.append('''echo "5/5 admin routes"
INT=$(aws apigatewayv2 get-routes --api-id $API --query "Items[?RouteKey=='GET /admin/players'].Target" --output text)
AUTH=$(aws apigatewayv2 get-routes --api-id $API --query "Items[?RouteKey=='GET /admin/players'].AuthorizerId" --output text)
for R in 'GET /admin/held' 'GET /admin/saves' 'POST /admin/restore' 'POST /admin/held/drop'; do
  [ -n "$(aws apigatewayv2 get-routes --api-id $API --query "Items[?RouteKey=='$R'].RouteId" --output text)" ] || \\
    aws apigatewayv2 create-route --api-id $API --route-key "$R" --authorization-type JWT --authorizer-id "$AUTH" --target "$INT" >/dev/null
done
B=https://$API.execute-api.us-east-1.amazonaws.com
for p in save mail/claim market/buy gulp admin/held; do curl -s -o /dev/null -w "$p %{http_code}\\n" $B/$p; done
echo "(401 means up and asking for sign-in)"
aws dynamodb describe-continuous-backups --table-name lanternhold-saves --query ContinuousBackupsDescription.PointInTimeRecoveryDescription.PointInTimeRecoveryStatus --output text
echo -e "done. Undo code:$UNDO"''')
open(os.path.join(here, 'save-checks.sh'), 'w').write('\n'.join(out) + '\n')
for fn, b64, md5, fp, n in parts: print(fn, n, 'bytes', md5)
